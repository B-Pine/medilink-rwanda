/// Makes the current [Strings] available below MaterialApp.
class S extends InheritedWidget {
  const S({super.key, required this.strings, required super.child});

  final Strings strings;

  static Strings of(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<S>()?.strings ?? Strings.rw;

  @override
  bool updateShouldNotify(S oldWidget) => oldWidget.strings.code != strings.code;
}
