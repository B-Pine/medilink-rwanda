#!/usr/bin/env node
/**
 * Generate TypeScript types from the backend's OpenAPI schema (docs/architecture/02 §7).
 *
 *   VITE_API_BASE_URL=http://localhost:8000 pnpm generate-types
 *
 * Writes src/generated/schema.d.ts. Sprint 0 still uses the hand-written src/types.ts (from the
 * contract); once the backend schema is live, alias those types to the generated ones and add a
 * CI step that fails when the committed file differs from a fresh generation (drift check).
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const baseUrl = (process.env.VITE_API_BASE_URL || "http://localhost:8000").replace(/\/+$/, "");
const schemaUrl = new URL("/api/v1/schema/", baseUrl);
const outFile = resolve(here, "../src/generated/schema.d.ts");

try {
  console.log(`Reading OpenAPI schema from ${schemaUrl.href}`);
  const ast = await openapiTS(schemaUrl);
  const banner =
    "/* eslint-disable */\n// Generated by `pnpm generate-types` (openapi-typescript). Do not edit by hand.\n\n";
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, banner + astToString(ast), "utf8");
  console.log(`Wrote ${outFile}`);
} catch (error) {
  console.error(
    `Could not generate types from ${schemaUrl.href}. Is the backend running (see backend/README.md)?`,
  );
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
