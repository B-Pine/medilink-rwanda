  /// The app's languages, in picker order, with their own names.
  static const languages = [('rw', 'Kinyarwanda'), ('en', 'English'), ('fr', 'Français')];

  static Strings forCode(String code) => switch (code) {
        'en' => en,
        'fr' => fr,
        _ => rw,
      };

  String state(String key) => stateLabels[key] ?? key;

  /// Picks this language from an API `*_i18n` map, falling back to English, then any value.
  String pick(Map<String, dynamic>? i18n) {
    if (i18n == null || i18n.isEmpty) return '';
    final value = i18n[code] ?? i18n['en'] ?? i18n.values.first;
    return value?.toString() ?? '';
  }
