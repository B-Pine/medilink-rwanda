@pytest.mark.acceptance("S5-B4")
def test_patient_hold_release_and_guards(
    clock: Clock, clinic: Any, bookable: dict[str, Any]
) -> None:
    client, user = patient_client("guards@example.test", "Guard Patient")
    slot = first_slot(clinic, bookable["service_id"], after=clock.now + dt.timedelta(hours=3))
    hold_id = _hold(client, f"{P}slots/{slot.pk}/hold/")
    assert client.delete(f"{P}holds/{hold_id}/").status_code == 204
    with rls_context(facility_id=clinic.pk):
        assert Slot.objects.get(pk=slot.pk).held_count == 0

    unknown = uuid.uuid4()
    assert client.delete(f"{P}holds/{unknown}/").status_code == 404
    assert client.post(f"{P}slots/{unknown}/hold/").status_code == 404
    expired = client.post(
        f"{P}bookings/",
        {"hold_id": str(unknown), "patient_id": self_id(user), "symptoms": [{"code": "fever"}]},
        format="json",
    )
    assert expired.status_code == 422 and error_code(expired) == "hold_expired"
    wrong_insurance = client.post(
        f"{P}bookings/",
        {
            "hold_id": _hold(client, f"{P}slots/{slot.pk}/hold/"),
            "patient_id": self_id(user),
            "symptoms": [{"code": "fever"}],
            "insurance_profile_id": str(unknown),
        },
        format="json",
    )
    assert wrong_insurance.status_code == 400
    assert client.post(f"{P}visits/{unknown}/arrived/").status_code == 404
    assert client.get(f"{P}bookings/?upcoming=false").status_code == 200

    public = APIClient()
    assert public.get(f"{PUB}facilities/{clinic.slug}/slots/").status_code == 404
    assert (
        public.get(f"{PUB}facilities/{clinic.slug}/slots/?service_id={unknown}").status_code == 404
    )
