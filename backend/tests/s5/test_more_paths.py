def _hold(client: APIClient, url: str) -> str:
    made = client.post(url)
    assert made.status_code == 201, made.content
    return made.json()["hold_id"]


@pytest.mark.acceptance("S5-B2")
def test_periodic_jobs_run_per_facility(
    clock: Clock, clinic: Any, bookable: dict[str, Any]
) -> None:
    assert tasks.refresh_facility(str(clinic.pk)) >= 1
    assert tasks.generate_slots() == 0  # already generated by the fixture
    assert tasks.refresh_public_listing() >= 1
    assert PublicListing.objects.filter(facility_id=clinic.pk).exists()

    client, user = patient_client("jobs@example.test", "Jobs Patient")
    slot = first_slot(clinic, bookable["service_id"], after=clock.now + dt.timedelta(hours=3))
    _hold(client, f"{P}slots/{slot.pk}/hold/")
    clock.now += dt.timedelta(minutes=30)  # past the 5-minute hold
    assert tasks.expire_holds() == 1

    other = first_slot(clinic, bookable["service_id"], after=clock.now + dt.timedelta(hours=3))
    booking = book(client, user, other).json()
    third = first_slot(
        clinic, bookable["service_id"], after=other.starts_at + dt.timedelta(minutes=1)
    )
    _hold(client, f"{P}slots/{third.pk}/hold/")  # an open hold lists the facility for the job
    clock.now = other.starts_at + dt.timedelta(days=1)  # no-show only once the facility closed (R4)
    assert tasks.mark_no_shows() == 1
    with rls_context(facility_id=clinic.pk):
        assert Booking.objects.get(pk=booking["id"]).status == BookingStatus.NO_SHOW
    assert tasks.pass_over() >= 0
    assert tasks.purge() >= 0


@pytest.mark.acceptance("S5-B6")
def test_staff_cancel_reschedule_and_list_filters(
    clock: Clock, clinic: Any, bookable: dict[str, Any], desk: tuple[APIClient, Any]
) -> None:
    staff = desk[0]
    record = register(clinic, desk[1], "Phone Rebook")
    week = staff.get(f"{S}slots/?service_id={bookable['service_id']}").json()
    open_slots = [s["id"] for d in week["days"] for s in d["slots"]]
    made = staff.post(
        f"{S}bookings/",
        {
            "hold_id": _hold(staff, f"{S}slots/{open_slots[0]}/hold/"),
            "facility_patient_id": str(record.pk),
            "contact_phone": "+250788123456",
            "symptoms": [{"code": "headache"}],
        },
        format="json",
    ).json()

    moved = staff.post(
        f"{S}bookings/{made['id']}/reschedule/",
        {"version": made["version"], "hold_id": _hold(staff, f"{S}slots/{open_slots[1]}/hold/")},
        format="json",
    )
    assert moved.status_code == 200, moved.content
    new = moved.json()
    assert new["id"] != made["id"] and new["status"] == "confirmed"

    day = new["starts_at"][:10]
    listed = staff.get(
        f"{S}bookings/?date={day}&service_id={bookable['service_id']}"
        f"&membership_id={bookable['membership'].pk}"
    ).json()
    assert [r["id"] for r in listed["results"]] == [new["id"]]  # the superseded one is hidden
    superseded = staff.get(f"{S}bookings/?date={made['starts_at'][:10]}&status=superseded")
    assert [r["id"] for r in superseded.json()["results"]] == [made["id"]]
    assert staff.get(f"{S}bookings/?date={day}&service_id=not-a-uuid").json()["count"] == 1

    no_reason = staff.post(
        f"{S}bookings/{new['id']}/cancel/",
        {"version": new["version"], "reason_code": "bored"},
        format="json",
    )
    assert no_reason.status_code == 422
    cancelled = staff.post(
        f"{S}bookings/{new['id']}/cancel/",
        {"version": new["version"], "reason_code": "facility_request"},
        format="json",
    )
    assert cancelled.status_code == 200 and cancelled.json()["status"] == "cancelled"
    closed = staff.post(
        f"{S}bookings/{new['id']}/reschedule/",
        {
            "version": cancelled.json()["version"],
            "hold_id": _hold(staff, f"{S}slots/{open_slots[2]}/hold/"),
        },
        format="json",
    )
    assert closed.status_code == 422 and error_code(closed) == "cancel_closed"

    unknown = uuid.uuid4()
    assert (
        staff.post(
            f"{S}bookings/{unknown}/cancel/", {"version": 1, "reason_code": "other"}, format="json"
        ).status_code
        == 404
    )
    assert staff.post(f"{S}slots/{unknown}/hold/").status_code == 404
    assert staff.get(f"{S}slots/").status_code == 404
    assert staff.get(f"{S}slots/?service_id={unknown}").status_code == 404
    assert (
        staff.post(
            f"{S}bookings/",
            {
                "hold_id": str(unknown),
                "facility_patient_id": str(unknown),
                "symptoms": [{"code": "headache"}],
            },
            format="json",
        ).status_code
        == 404
    )


@pytest.mark.acceptance("S5-B4")
def test_staff_hold_on_a_full_slot_offers_alternatives(
    clock: Clock, clinic: Any, bookable: dict[str, Any], desk: tuple[APIClient, Any]
) -> None:
    slot = first_slot(clinic, bookable["service_id"], after=clock.now + dt.timedelta(hours=3))
    patient, _ = patient_client("first@example.test", "First Caller")
    _hold(patient, f"{P}slots/{slot.pk}/hold/")  # the one bookable place
